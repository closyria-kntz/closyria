import { motionDurationKeys } from "./semantic";
import { equilibreDark, equilibreLight, type Theme } from "./theme";

function declarations(tokens: Record<string, string | undefined>, indent: string): string {
  return Object.entries(tokens)
    .map(([key, value]) => `${indent}--${key}: ${value};`)
    .join("\n");
}

function reducedMotion(selector: string): string {
  const zeroed = Object.fromEntries(motionDurationKeys.map((key) => [key, "0ms"]));
  return `@media (prefers-reduced-motion: reduce) {\n  ${selector} {\n${declarations(zeroed, "    ")}\n  }\n}`;
}

/**
 * CSS variables of a theme under `[data-theme="<id>"]`, its `color-scheme` (the browser's scroll bars and native
 * controls follow it), plus the reduced-motion override.
 */
export function renderThemeCss(theme: Theme): string {
  const selector = `[data-theme="${theme.id}"]`;
  return `${selector} {\n  color-scheme: ${theme.base};\n${declarations(theme.tokens, "  ")}\n}\n\n${reducedMotion(selector)}\n`;
}

/**
 * The whole generated stylesheet for Tailwind:
 * - `@theme static` resets Tailwind's defaults and declares the default theme on `:root`;
 * - one block per theme;
 * - the dark theme also follows the system preference unless the light theme is forced.
 */
export function renderTokensCss(): string {
  const base = equilibreLight.tokens;
  const darkVars = declarations(equilibreDark.tokens, "    ");
  return [
    "/* Generated by @closyria/design-tokens (scripts/build-css.ts). Do not edit. */",
    `@theme static {\n  --*: initial;\n${declarations(base, "  ")}\n}`,
    `:root {\n  color-scheme: light;\n}`,
    reducedMotion(":root"),
    renderThemeCss(equilibreLight),
    renderThemeCss(equilibreDark),
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="equilibre-light"]) {\n    color-scheme: dark;\n${darkVars}\n  }\n}\n`,
  ].join("\n\n");
}
