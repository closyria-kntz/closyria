// Bundles docs/legal/conditions-referencement.md into packages/shared (accords en ligne, 2026-11-14): the API records
// the version and the SHA-256 of exactly the text the page shows. Run `node scripts/listing-conditions.ts` after
// editing the conditions; scripts/listing-conditions.test.ts fails while the bundled copy is stale.
// Runs under Node's native type stripping: keep explicit .ts imports and no TS-only runtime syntax.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SOURCE = fileURLToPath(new URL("../docs/legal/conditions-referencement.md", import.meta.url));
export const TARGET = fileURLToPath(new URL("../packages/shared/src/listing-conditions.generated.ts", import.meta.url));

const VERSION_LINE = /^Version : (v\d+) — (\d{4}-\d{2}-\d{2})$/m;

/** The TypeScript module holding the conditions: version, date, SHA-256 (hex, of the UTF-8 text) and the text. */
export function conditionsModule(markdown: string): string {
  const found = VERSION_LINE.exec(markdown);
  if (!found) throw new Error("conditions-referencement.md: no « Version : vN — AAAA-MM-JJ » line");
  const sha256 = createHash("sha256").update(markdown, "utf8").digest("hex");
  return [
    "// Generated by scripts/listing-conditions.ts from docs/legal/conditions-referencement.md: do not edit.",
    "export const LISTING_CONDITIONS = {",
    `  version: ${JSON.stringify(found[1])},`,
    `  date: ${JSON.stringify(found[2])},`,
    `  sha256: ${JSON.stringify(sha256)},`,
    "  markdown:",
    `    ${JSON.stringify(markdown)},`,
    "} as const;",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TARGET, conditionsModule(readFileSync(SOURCE, "utf8")));
  console.log(`wrote ${TARGET}`);
}
